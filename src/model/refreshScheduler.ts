// RefreshScheduler (WP-1.8): WHEN a repository refreshes. Three watchers drive offline/online
// status after a debounce, and a focused remote poll runs every intervalSeconds. Type-only
// vscode imports: the watchers, focus, clock and config are injected (the VS Code adapters
// live in model.ts), so plain mocha tests drive it with fake timers.
import type { Disposable, Event, Uri } from "vscode";
import type { AuthState, StatusDoc } from "../contract/types";
import type { ContexoConfig } from "../services";

/** The three watcher globs, relative to the workspace folder (E28: never the credentials literal). */
export const WATCH_GLOBS = {
  /** (a) page files: create/change/delete -> offline refresh. */
  md: ".contexo/**/*.md",
  /** (b) .contexo/config.json, credentials, …: any event -> ONLINE refresh. Depth 1, so never .sync/*.json. */
  json: ".contexo/*.json",
  /** (c) capture buffers (*.jsonl): create/delete -> offline refresh; created with ignoreChangeEvents. */
  pending: ".contexo/raw/sessions/_pending/*",
} as const;

/** Trailing debounce per watcher, plus a max wait so a continuous event storm still refreshes. */
export const DEBOUNCE = {
  md: { delayMs: 1_000, maxWaitMs: 5_000 },
  json: { delayMs: 1_000, maxWaitMs: 5_000 },
  pending: { delayMs: 5_000, maxWaitMs: 15_000 },
} as const;

/** remote.error rate_limited doubles the poll interval up to this many seconds. */
export const MAX_BACKOFF_SECONDS = 900;

export interface Clock {
  now(): number;
  setTimeout(fn: () => void, ms: number): unknown;
  clearTimeout(handle: unknown): void;
}

/** The real clock (globalThis timers, read at call time so sinon fake timers also reach it). */
export const systemClock: Clock = {
  now: () => Date.now(),
  setTimeout: (fn, ms) => setTimeout(fn, ms),
  clearTimeout: (handle) => clearTimeout(handle as ReturnType<typeof setTimeout>),
};

/** The part of vscode.FileSystemWatcher the scheduler uses. */
export interface FileEventSource extends Disposable {
  readonly onDidCreate: Event<Uri>;
  readonly onDidChange: Event<Uri>;
  readonly onDidDelete: Event<Uri>;
}

/** Window focus (vscode.window.state.focused + onDidChangeWindowState). */
export interface FocusSource {
  readonly focused: boolean;
  readonly onDidChange: Event<boolean>;
}

export interface RefreshSchedulerDeps {
  clock: Clock;
  focus: FocusSource;
  config: Pick<ContexoConfig, "remoteRefreshEnabled" | "remoteRefreshIntervalSeconds" | "onDidChange">;
  /** The repository's watchers, created over WATCH_GLOBS (pending with ignoreChangeEvents). */
  watchers: { md: FileEventSource; json: FileEventSource; pending: FileEventSource };
  /** '/'-separated path of uri relative to <root>/.contexo, or undefined when outside it. */
  relPathOf(uri: Uri): string | undefined;
  /** Ask the repository for a refresh (it coalesces). A returned promise is not awaited. */
  refresh(o: { remote: boolean }): Promise<void> | void;
  /** The repository's latest auth.state; undefined before its first status. */
  authState(): AuthState | undefined;
  /** For the .sync segment case rule (default process.platform). */
  platform?: NodeJS.Platform;
}

